// Regenerates mobile/src/lib/word-images.ts. (Learning content itself comes from scripts/generate-mobile-content.mjs.)
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Word pictures (mobile/assets/word-images/<word-id>.jpg, e.g. generated with scripts/generate_word_images.py).
const { existsSync } = await import("node:fs");
const imagesDirectory = path.join(root, "mobile", "assets", "word-images");
const images = existsSync(imagesDirectory) ? (await readdir(imagesDirectory)).filter((file) => /^[a-z0-9_]+\.jpg$/.test(file)).sort() : [];
const imageLines = [
  "// AUTO-GENERATED by scripts/generate-mobile-packs.mjs – do not edit.",
  "// Word pictures from mobile/assets/word-images/<word-id>.jpg (created with ComfyUI, see scripts/generate_word_images.py).",
  images.length ? "export const WORD_IMAGES: Record<string, number> = {" : "export const WORD_IMAGES: Record<string, number> = {};",
  ...images.map((file) => `  ${path.basename(file, ".jpg")}: require("../../assets/word-images/${file}"),`),
  ...(images.length ? ["};"] : []),
];
await writeFile(path.join(root, "mobile", "src", "lib", "word-images.ts"), `${imageLines.join("\n")}\n`);
console.log(`word-images.ts aktualisiert (${images.length} Bilder).`);

// City artwork (mobile/assets/city/<building>_<stage>.png, from scripts/generate_city_images.py).
const cityDirectory = path.join(root, "mobile", "assets", "city");
const cityImages = existsSync(cityDirectory) ? (await readdir(cityDirectory)).filter((file) => /^[a-z]+_\d\.png$/.test(file)).sort() : [];
const cityLines = [
  "// AUTO-GENERATED by scripts/generate-mobile-packs.mjs – do not edit.",
  "// Building and decoration pictures from mobile/assets/city/<id>_<stage>.png (scripts/generate_city_images.py).",
  cityImages.length ? "export const CITY_IMAGES: Record<string, number> = {" : "export const CITY_IMAGES: Record<string, number> = {};",
  ...cityImages.map((file) => `  ${path.basename(file, ".png")}: require("../../assets/city/${file}"),`),
  ...(cityImages.length ? ["};"] : []),
];
await writeFile(path.join(root, "mobile", "src", "lib", "city-images.ts"), `${cityLines.join("\n")}\n`);
console.log(`city-images.ts aktualisiert (${cityImages.length} Bilder).`);
